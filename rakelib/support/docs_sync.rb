# Converts the Docusaurus site in omniagent-docs/docs into plain Markdown under
# docs/, which ships inside the gem so coding agents working in a host app can
# read it offline (see `omni_agent docs`). Development-only: rakelib/ is not
# packaged with the gem.
require "json"
require "pathname"

module DocsSync
  ROOT = File.expand_path("../..", __dir__)
  SOURCE = File.join(ROOT, "omniagent-docs", "docs")
  TARGET = File.join(ROOT, "docs")
  SITE_URL = "https://omniagent.activetaskers.com/docs"

  INDEX_PREAMBLE = <<~MARKDOWN
    # OmniAgent Documentation

    Offline copy of #{SITE_URL}/intro, bundled with the `omni_agent` gem so coding
    agents (Claude Code, Cursor, Codex...) can learn how the gem works from inside
    a project that depends on it. Every page is plain Markdown; links between
    pages are relative.

    Locate these files from a host app with:

    ```bash
    bundle exec omni_agent docs          # print this index
    bundle exec omni_agent docs tools    # print one page (path without .md)
    bundle exec omni_agent docs --path   # print the directory holding these files
    ```

    ## Conventions at a Glance

    OmniAgent is convention over configuration: classes are discovered from
    where they live, so put files where the generators put them.

    | What | Where | Class |
    | --- | --- | --- |
    | Global settings | `config/initializers/omni_agent.rb` (written by `omni_agent:install`) | `OmniAgent.configure` |
    | Agent | `app/agents/<name>.rb` | `<Name> < OmniAgent::Agent` |
    | Agent system prompt | `app/agents/<name>/prompt.md.erb` | |
    | Entrypoint prompt | `app/agents/<name>/<entrypoint>.md.erb` | |
    | Agent tool | `app/agents/<name>/tools/<tool>.rb` | `<Name>::Tools::<Tool> < OmniAgent::Tool` |
    | MCP server | `app/mcp_servers/<name>_server.rb` | `<Name>Server < OmniAgent::MCP::Server` |
    | MCP server tool | `app/mcp_servers/<name>_server/tools/<tool>.rb` | `<Name>Server::Tools::<Tool>` |
    | Eval | `evals/<name>_eval.rb` | `< OmniAgent::Eval` |

    Prefer the generators (`rails generate omni_agent:agent`, `omni_agent:mcp_server`,
    `omni_agent:stock_agent`, `omni_agent:eval`, `omni_agent:embeddings`,
    `omni_agent:chunks`) over writing these files by hand.
    See [Generators](generators.md).

    ## Typical Flows

    * **Build an agent:** [Introduction](intro.md) → [Tools](tools.md) →
      [Run Entrypoints](agent/run-entrypoints.md) → [Structured Output](agent/structured-output.md).
    * **Pick a provider or model:** [Supported Providers](supported-providers.md),
      [Configuration](configuration.md), [Change an Agent's Provider or Model](agent/provider.md).
    * **Compose agents:** [Multi-Agent Delegation](agent/delegation.md),
      [Stock Agents](stock-agents/overview.md).
    * **Observe a run:** [Generation Callbacks](agent/callbacks.md),
      [Streaming Responses](agent/streaming.md).
    * **Answer from your own data (RAG):** [Retrieval-Augmented Generation](rag.md)
      (`has_embedding`, `has_chunks` and the `searches` agent macro).
    * **Test quality:** [Generating and Running Evals](evals/generating-and-running.md) →
      [Golden Sets](evals/golden-sets.md) → [Judge Provider](evals/judge-provider.md).
    * **Expose tools to MCP clients:** [Defining MCP Servers](mcp/defining-servers.md) →
      [Authentication](mcp/authentication.md) → [Transports and Clients](mcp/transports.md).

    ## All Pages
  MARKDOWN

  Page = Struct.new(:source, :relative, :title, :summary, :position, keyword_init: true) do
    def target_relative
      relative.sub(/\.mdx?\z/, ".md")
    end
  end

  module_function

  # Returns { "relative/path" => contents } for every file that should exist
  # under docs/: the index, one Markdown page per doc, and any other files in
  # the site's docs folder (images and the like) copied as-is.
  def build
    entries = tree(SOURCE, "")
    anchors = category_anchors(entries)
    files = { "index.md" => index(entries) }
    each_page(entries) { |page| files[page.target_relative] = convert(page, anchors) }
    assets.each { |relative| files[relative] = File.binread(File.join(SOURCE, relative)) }
    files
  end

  def write!(target = TARGET)
    files = build
    stale = Dir.glob("**/*", base: target).reject { |path| File.directory?(File.join(target, path)) } - files.keys
    stale.each { |path| File.delete(File.join(target, path)) }
    files.each do |path, contents|
      full = File.join(target, path)
      FileUtils.mkdir_p(File.dirname(full))
      File.binwrite(full, contents)
    end
    files.keys
  end

  # Sorted list of pages and categories, mirroring the autogenerated sidebar.
  # A folder without _category_.json is still a category (labelled after the
  # folder, sorted last), and one with no pages is left out of the index.
  def tree(dir, prefix)
    entries = Dir.children(dir).sort.filter_map do |name|
      path = File.join(dir, name)
      relative = prefix.empty? ? name : File.join(prefix, name)

      if File.directory?(path)
        category(path, relative)
      elsif name.end_with?(".md", ".mdx")
        page(path, relative)
      end
    end
    entries.sort_by { |entry| [ entry.is_a?(Page) ? entry.position : entry[:position], entry.is_a?(Page) ? entry.relative : entry[:label] ] }
  end

  def category(path, relative)
    children = tree(path, relative)
    return if children.empty?

    config_file = File.join(path, "_category_.json")
    config = File.exist?(config_file) ? JSON.parse(File.read(config_file)) : {}
    label = config["label"] || File.basename(path)
    slug = config.dig("link", "slug")&.delete_prefix("/") || "category/#{docusaurus_slug(label)}"

    { type: :category, label: label, slug: slug, position: (config["position"] || Float::INFINITY).to_f,
      description: config.dig("link", "description"), children: children }
  end

  def assets
    Dir.glob("**/*", base: SOURCE).reject do |relative|
      File.directory?(File.join(SOURCE, relative)) || relative.end_with?(".md", ".mdx") || File.basename(relative) == "_category_.json"
    end.sort
  end

  def page(path, relative)
    raw = File.read(path)
    frontmatter = raw[/\A---\n(.*?)\n---\n/m, 1].to_s
    body = raw.sub(/\A---\n.*?\n---\n/m, "")
    title = body[/^# (.+)$/, 1].to_s.strip
    after_title = body.split(/^# .+$/, 2).last.to_s
    summary = after_title.strip.split(/\n\s*\n/).first.to_s.gsub(/\s+/, " ").gsub(/\[([^\]]+)\]\([^)]+\)/, '\1').strip.sub(/:\z/, ".")
    position = frontmatter[/^sidebar_position:\s*([\d.]+)/, 1].to_f

    Page.new(source: path, relative: relative, title: title, summary: summary, position: position)
  end

  def each_page(entries, &block)
    entries.each do |entry|
      entry.is_a?(Page) ? block.call(entry) : each_page(entry[:children], &block)
    end
  end

  # { "category/<docusaurus slug>" => "<anchor of the category's heading in index.md>" }
  # Only top-level categories get a heading in the index, so links to nested
  # ones raise in rewrite_links.
  def category_anchors(entries)
    entries.reject { |entry| entry.is_a?(Page) }.to_h { |category| [ category[:slug], heading_anchor(category[:label]) ] }
  end

  # How Docusaurus turns a category label into its generated-index slug.
  def docusaurus_slug(label)
    label.downcase.gsub(/[^a-z0-9]+/, "-").gsub(/\A-|-\z/, "")
  end

  # How GitHub (and most Markdown renderers) turn a heading into an anchor.
  def heading_anchor(text)
    text.downcase.gsub(/[^\p{Word}\- ]/, "").tr(" ", "-")
  end

  def index(entries)
    # Top-level pages go first under their own heading so a page sorted after a
    # category doesn't read as part of it.
    pages, categories = entries.partition { |entry| entry.is_a?(Page) }
    lines = [ "### Core", "" ] + pages.map { |page| index_line(page) }
    categories.each do |category|
      lines << "" << "### #{category[:label]}" << ""
      lines << category[:description] << "" if category[:description]
      each_page(category[:children]) { |page| lines << index_line(page) }
    end
    "#{INDEX_PREAMBLE}\n#{lines.join("\n")}\n"
  end

  def index_line(page)
    "* [#{page.title}](#{page.target_relative}): #{page.summary}"
  end

  def convert(page, category_anchors)
    body = File.read(page.source).sub(/\A---\n.*?\n---\n/m, "").sub(/\A\s+/, "")
    body = convert_admonitions(body)
    body = rewrite_links(body, page, category_anchors)
    header = "<!-- Generated from omniagent-docs/docs/#{page.relative} by `bundle exec rake docs:sync`. Do not edit by hand. -->\n" \
             "<!-- Online version: #{SITE_URL}/#{page.relative.sub(/\.mdx?\z/, "")} -->\n\n"
    "#{header}#{body.rstrip}\n"
  end

  # Docusaurus `:::type Title ... :::` blocks become blockquotes.
  def convert_admonitions(body)
    body.gsub(/^:::(\w+)[ \t]*(.*?)\n(.*?)^:::[ \t]*$/m) do
      kind = Regexp.last_match(1).capitalize
      title = Regexp.last_match(2).strip
      content = Regexp.last_match(3).strip
      heading = title.empty? ? "**#{kind}**" : "**#{kind}: #{title}**"
      ([ heading, "" ] + content.lines.map(&:chomp)).map { |line| line.empty? ? ">" : "> #{line}" }.join("\n")
    end
  end

  # Turns links to other docs into relative .md links. Links to anything else
  # (images and other assets) keep their relative path, since docs/ mirrors the
  # site's folder layout.
  def rewrite_links(body, page, category_anchors)
    current_dir = Pathname.new(File.dirname(page.target_relative))

    body.gsub(/\]\(((?:\/docs\/|\.{1,2}\/)[^)\s#]*)(#[^)\s]*)?\)/) do |link|
      target = Regexp.last_match(1)
      anchor = Regexp.last_match(2).to_s
      next link unless [ "", ".md", ".mdx" ].include?(File.extname(target))

      resolved =
        if target.start_with?("/docs/category/")
          slug = target.delete_prefix("/docs/")
          anchor = "##{category_anchors.fetch(slug) { raise "Unknown category link #{target} in #{page.relative}" }}"
          "index.md"
        elsif target.start_with?("/docs/")
          "#{target.delete_prefix("/docs/").sub(/\.mdx?\z/, "")}.md"
        else
          "#{(current_dir + target).cleanpath.to_s.sub(/\.mdx?\z/, "")}.md"
        end

      "](#{Pathname.new(resolved).relative_path_from(current_dir)}#{anchor})"
    end
  end
end
